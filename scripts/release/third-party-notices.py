FOOTER = """## Rust standard library

The static libraries also contain the Rust standard library, `compiler_builtins` and the crates the
toolchain bundles (`gimli`, `object`, `addr2line`, `miniz_oxide`, `rustc_demangle`, ...). Their
notices are in the toolchain: `share/doc/rust/COPYRIGHT-library.html` and `licenses/` under the
`rustc --print sysroot` directory. They are not reproduced here.
"""


def linked_packages():
    meta = json.loads(subprocess.check_output(
        ["cargo", "metadata", "--format-version", "1", "--locked", "--offline"], cwd=ROOT, stderr=subprocess.DEVNULL))
    pk = {(p["name"], p["version"]): p for p in meta["packages"]}
    found = set()
    for target in IOS_TARGETS:
        txt = subprocess.check_output(
            ["cargo", "tree", "-p", "laniakea-uniffi", "--target", target, "-e", "normal", "--prefix", "none", "--format", "{p}"],
            cwd=ROOT, stderr=subprocess.DEVNULL, text=True)
        for line in txt.splitlines():
            m = re.match(r"(\S+) v(\S+)( \(proc-macro\))?( \(.*\))?", line)
            if m and not m.group(3) and (m.group(1), m.group(2)) in pk:
                found.add((m.group(1), m.group(2)))
    members = {p["name"] for p in meta["packages"] if p["source"] is None}
    return [pk[k] for k in sorted(found) if k[0] not in members]


def clean(raw):
    lines = raw.decode("utf-8", "replace").replace("\r\n", "\n").split("\n")
    return "\n".join(l.rstrip() for l in lines).rstrip("\n") + "\n"


def build():
    lock = open(os.path.join(ROOT, "Cargo.lock"), "rb").read()
    pkgs = linked_packages()
    manifest = os.path.join(UPSTREAM, "MANIFEST.tsv")
    up = [l.rstrip("\n").split("\t") for l in open(manifest)][1:] if os.path.exists(manifest) else []
    upstream_for = {}  # (crate, version) -> [(file, url, text)]
    for crates, ver, fname, url, sha in up:
        data = open(os.path.join(UPSTREAM, fname), "rb").read()
        if hashlib.sha256(data).hexdigest() != sha:
            sys.exit("docs/third-party-upstream/%s does not match MANIFEST.tsv" % fname)
        for c in crates.split(","):
            upstream_for.setdefault((c, ver), []).append((fname, url, clean(data)))

    texts = {}  # sha256 of text -> [text, [(crate version, file, origin)]]
    rows, missing = [], []
    for p in pkgs:
        d = os.path.dirname(p["manifest_path"])
        files = sorted(f for f in os.listdir(d) if LICENCE_FILE.match(f) and os.path.isfile(os.path.join(d, f)))
        found = [(f, "the crate", clean(open(os.path.join(d, f), "rb").read())) for f in files]
        if not found:
            found = [(f, url, t) for f, url, t in upstream_for.get((p["name"], p["version"]), [])]
        if not found:
            missing.append("%s %s" % (p["name"], p["version"]))
        for f, origin, t in found:
            texts.setdefault(hashlib.sha256(t.encode()).hexdigest(), [t, []])[1].append(("%s %s" % (p["name"], p["version"]), f, origin))
        rows.append((p["name"], p["version"], p["license"] or "(see texts)", "crate" if files else "upstream: " + ", ".join(sorted({u for _, u, _ in found}))[:90]))
    if missing:
        sys.exit("no licence text for: %s (add it to docs/third-party-upstream/ with a MANIFEST.tsv row, then --write)" % ", ".join(missing))

    ark_mit = clean(open(os.path.join(ROOT, "vendor", "ark-circom", "LICENSE-MIT"), "rb").read()).rstrip("\n")
    head = HEADER.format(lock=hashlib.sha256(lock).hexdigest()).replace(
        "@@ARK_CIRCOM_MIT@@",
        "From `vendor/ark-circom/LICENSE-MIT` (identical to the crates.io `ark-circom` 0.1.0 file; its stray trailing "
        "characters are upstream's). The same copyright line heads `LICENSE-APACHE`.\n\n~~~~text\n" + ark_mit + "\n~~~~")
    o = [head]
    o.append("### Crates\n")
    o.append("| Crate | Version | Declared licence | Text from |")
    o.append("|---|---|---|---|")
    o += ["| %s | %s | %s | %s |" % r for r in rows]
    o.append("")
    o.append("### Licence texts (%d distinct)\n" % len(texts))
    for n, (h, (t, users)) in enumerate(sorted(texts.items(), key=lambda kv: sorted(kv[1][1])[0]), 1):
        users = sorted(users)
        o.append("#### Text %d\n" % n)
        o.append("Shipped as: " + "; ".join("%s in %s (from %s)" % (f, c, org if org == "the crate" else "upstream") for c, f, org in users) + "\n")
        o.append("~~~~text\n" + t.rstrip("\n") + "\n~~~~\n")
    o.append(FOOTER)
    return "\n".join(o).rstrip("\n") + "\n"


def main():
    mode = sys.argv[1] if len(sys.argv) > 1 else ""
    if mode not in ("", "--write", "--check"):
        sys.exit(__doc__)
    text = build()
    if mode == "--write":
        open(OUT, "w").write(text)
        print("wrote", os.path.relpath(OUT, ROOT))
    elif mode == "--check":
        if not os.path.exists(OUT) or open(OUT).read() != text:
            sys.exit("THIRD_PARTY_NOTICES.md is missing or out of date; run scripts/release/third-party-notices.py --write")
        print("THIRD_PARTY_NOTICES.md is up to date")
    else:
        sys.stdout.write(text)


main()
